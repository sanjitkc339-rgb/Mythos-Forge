CREATE TABLE IF NOT EXISTS worlds (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  genre VARCHAR(70) NOT NULL,
  premise VARCHAR(320) NOT NULL,
  seed BIGINT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS world_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  world_id BIGINT NOT NULL,
  kind VARCHAR(20) NOT NULL,
  name VARCHAR(90) NOT NULL,
  subtitle VARCHAR(100) NOT NULL,
  description VARCHAR(800) NOT NULL,
  traits VARCHAR(240) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT fk_world_items_world FOREIGN KEY (world_id) REFERENCES worlds(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS world_links (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  world_id BIGINT NOT NULL,
  source_id BIGINT NOT NULL,
  target_id BIGINT NOT NULL,
  label VARCHAR(70) NOT NULL,
  CONSTRAINT fk_world_links_world FOREIGN KEY (world_id) REFERENCES worlds(id) ON DELETE CASCADE,
  CONSTRAINT fk_world_links_source FOREIGN KEY (source_id) REFERENCES world_items(id) ON DELETE CASCADE,
  CONSTRAINT fk_world_links_target FOREIGN KEY (target_id) REFERENCES world_items(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_world_items_world ON world_items(world_id);
CREATE INDEX IF NOT EXISTS idx_world_links_world ON world_links(world_id);
